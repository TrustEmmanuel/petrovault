function openTransfer(
  movements: Movement[],
  movementId: string,
  itemId: string,
  quantity: number,
  from: Location,
  to: Location,
  wellId: string,
): Transfer {
  const movement = movements.find((row) => row.id === movementId);
  const item = items.find((row) => row.id === itemId);
  if (!movement || !item) throw new Error(`Bad transfer seed ${movementId}`);
  return {
    id: `tr_${movementId}`,
    itemId,
    itemName: item.name,
    sku: item.sku,
    quantity,
    unit: item.unit,
    unitCost: item.unitCost,
    from,
    to,
    wellId,
    status: "In Transit",
    departedAt: movement.at,
    reference: movement.reference,
    actor: movement.actor,
  };
}

function reorder(
  id: string,
  itemId: string,
  quantity: number,
  vendor: string,
  status: Reorder["status"],
  requestedAt: string,
  note: string,
  decidedAt?: string,
  decidedBy?: string,
): Reorder {
  const item = items.find((row) => row.id === itemId);
  if (!item) throw new Error(itemId);
  return {
    id,
    itemId,
    itemName: item.name,
    sku: item.sku,
    quantity,
    unit: item.unit,
    unitCost: item.unitCost,
    vendor,
    status,
    requestedAt,
    requestedBy: storekeeper,
    note,
    ...(decidedAt ? { decidedAt, decidedBy } : {}),
  };
}

